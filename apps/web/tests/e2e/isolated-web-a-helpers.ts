/**
 * Shared helpers for the *-isolated-web-a.spec.ts walks
 * (.github/workflows/signup-isolated.yml). Everything here talks to the
 * THROWAWAY local stack only: the app on 127.0.0.1, the local Supabase on
 * 127.0.0.1:54321, its database container, and the local mail catchers.
 * Nothing leaves the runner; production hosts are blackholed by the job.
 */

export const BASE = process.env.E2E_BASE_URL ?? "";
export const SB_URL = process.env.E2E_SUPABASE_URL ?? "";
export const SB_SERVICE = process.env.E2E_SUPABASE_SERVICE_ROLE_KEY ?? "";
export const SB_ANON = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ?? "";
export const LOCAL = /^http:\/\/127\.0\.0\.1:\d+$/;
/** The local stack's own mail catcher — auth mail (verification, reset). */
export const STACK_MAIL = "http://127.0.0.1:54324";
export const PASSWORD = "Synthetic-Pass-2026!";

/** True only on the isolated CI stack (SIGNUP_ISOLATED=1, everything local). */
export function isolatedStack(): boolean {
  return (
    process.env.SIGNUP_ISOLATED === "1" &&
    LOCAL.test(BASE) &&
    SB_URL === "http://127.0.0.1:54321" &&
    !!SB_SERVICE
  );
}

const DB_CONTAINER = "supabase_db_labourmarketai";

/**
 * One read on the LOCAL database as its superuser, through the stack's own
 * container (the same door the workflow's replay proof uses). Grants are not
 * the question these walks ask — the stored rows are — so the check does not
 * depend on which role may SELECT a table. Literal values only, generated by
 * the spec itself; the result is JSON rows.
 */
export function sql<T>(query: string): T[] {
  const wrapped = `select coalesce(json_agg(t), '[]'::json) from (${query}) t`;
  const out = execFileSync("docker", ["exec", DB_CONTAINER, "psql", "-U", "postgres", "-tA", "-c", wrapped], {
    encoding: "utf8",
  });
  return JSON.parse(out.trim() || "[]") as T[];
}

/** One statement on the LOCAL database (setup in the throwaway stack only). */
export function sqlExec(statement: string): void {
  execFileSync("docker", ["exec", DB_CONTAINER, "psql", "-U", "postgres", "-v", "ON_ERROR_STOP=1", "-tA", "-c", statement], {
    encoding: "utf8",
  });
}

/** A literal for sql(): single quotes doubled. Values come from the spec only. */
export function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

export async function userId(address: string): Promise<string> {
  const rows = sql<{ id: string }>(`select id from auth.users where email = ${lit(address)}`);
  if (!rows[0]) throw new Error("no local auth user for the walk's address");
  return rows[0].id;
}

