import { chromium } from "@playwright/test";
const base = "http://127.0.0.1:3100";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
const page = await ctx.newPage(); page.setDefaultTimeout(180000); page.setDefaultNavigationTimeout(240000);
await page.goto(base + "/en/auth/login", { waitUntil: "domcontentloaded" });
await page.waitForLoadState("networkidle").catch(()=>{});
await page.locator('input[type="email"]').fill(process.argv[2]);
await page.locator('input[type="password"]').fill("Pw-chain-qa-1!");
await page.locator('button[type="submit"]').first().click();
await page.waitForURL(/dashboard/);
await page.waitForLoadState("networkidle").catch(()=>{});
await page.waitForTimeout(3000);
const btn = page.getByRole("button", { name: /Workspace:/ });
console.log("workspace btn:", await btn.innerText());
await btn.click();
await page.waitForTimeout(1500);
console.log(await page.locator('[role="menu"], [role="listbox"], [role="dialog"]').allInnerTexts());
await page.screenshot({ path: "../../qa-shots/explore-ws.png" });
console.log(await page.evaluate(() => [...document.querySelectorAll('[data-testid*="workspace"]')].map(e => e.getAttribute("data-testid")+":"+(e.innerText||"").slice(0,40)).join("\n")));
const opt = page.getByTestId("workspace-option-f35935ea-7985-4bc1-8578-32055d68e4ac");
await opt.click();
await page.waitForTimeout(6000);
console.log("after click:", await page.getByRole("button", { name: /Workspace:/ }).innerText(), page.url());
