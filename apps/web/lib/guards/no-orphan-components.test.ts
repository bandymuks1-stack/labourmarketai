const isTestPath = (rel: string) =>
  /\.(test|spec)\.[cm]?[tj]sx?$/.test(rel) || rel.includes("/guards/") || rel.includes("__tests__");

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|mjs|js)$/.test(name)) out.push(p);
  }
  return out;
}

function resolveSpecifier(from: string, spec: string): string | null {
  let base: string;
  if (spec.startsWith("@/")) base = join(WEB, spec.slice(2));
  else if (spec.startsWith(".")) base = resolve(dirname(from), spec);
  else return null;
  for (const candidate of [
    base,
    `${base}.tsx`,
    `${base}.ts`,
    `${base}.mjs`,
    `${base}.js`,
    join(base, "index.tsx"),
    join(base, "index.ts"),
  ]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

/** Static imports, `export … from`, dynamic `import()` and `require()`. */
const SPECIFIER = /(?:from\s*|import\s*\(\s*|require\s*\(\s*|import\s+)["'`]([^"'`]+)["'`]/g;

function productImported(): Set<string> {
  const imported = new Set<string>();
  const sources = PRODUCT_DIRS.filter((d) => existsSync(join(WEB, d))).flatMap((d) => walk(join(WEB, d)));
  for (const file of sources) {
    if (isTestPath(relative(WEB, file))) continue;
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(SPECIFIER)) {
      const target = resolveSpecifier(file, m[1]);
      if (target && target !== file) imported.add(relative(WEB, target));
    }
  }
  return imported;
}

const COMPONENTS = walk(join(WEB, "components"))
  .map((p) => relative(WEB, p))
  .filter((rel) => !isTestPath(rel))
  .sort();
const IMPORTED = productImported();
const ORPHANS = COMPONENTS.filter((rel) => !IMPORTED.has(rel));

describe("no orphan components (R1)", () => {
  it("the scan sees the component tree and the import graph", () => {
    expect(COMPONENTS.length, "components/ files found").toBeGreaterThan(200);
    expect(IMPORTED.size, "product-imported files found").toBeGreaterThan(500);
    // Negative control: a file mounted by the dashboard layout is seen as imported.
    expect(IMPORTED.has("components/app/conversation/chat/conversation-header.tsx")).toBe(true);
  });

  it("every component outside KNOWN_ORPHANS has a product importer", () => {
    const unexpected = ORPHANS.filter((rel) => !KNOWN_ORPHANS.includes(rel));
    expect(
      unexpected,
      "These components are imported by no product code. Mount them where they are used, or delete them " +
        "(with the guards that pin them). Do not add them to KNOWN_ORPHANS.",
    ).toEqual([]);
  });

  it("KNOWN_ORPHANS only shrinks: every entry still exists and is still an orphan", () => {
    const stale = KNOWN_ORPHANS.filter((rel) => !existsSync(join(WEB, rel)) || IMPORTED.has(rel));
    expect(stale, "Remove these from KNOWN_ORPHANS: they were deleted or are imported again.").toEqual([]);
  });
});
